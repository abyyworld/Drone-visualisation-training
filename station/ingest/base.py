"""Frame, source metadata, and the abstract base every video source implements.

This module is the adapter seam of the whole system. Everything downstream --
inference, the temporal filter, the WebRTC track, the incident log -- consumes
:class:`Frame` objects and never knows whether they came off a drone radio, a
capture card, or a file on disk. That is what lets the pipeline be developed
and regression-tested with no drone in the room.

**pts is the contract.** ``Frame.pts`` is presentation time in seconds on the
*media* timeline: the same timeline the browser exposes as
``video.currentTime`` and the same number that goes into
``FrameDetections.pts``. It is the only field that lets a tablet draw a box
over the frame it was computed from (see ``docs/CONTRACT.md``). Three
properties are guaranteed here and relied upon everywhere else:

1. **Zero-based.** The first frame emitted in a session has ``pts == 0.0``.
   Containers may start at an arbitrary offset; live sources restart from zero
   on every reconnect. Rebasing once, here, means the rest of the system has a
   single continuous timeline and ``stream_start_pts`` is meaningful.
2. **Strictly monotonic.** ``pts`` never repeats and never goes backwards --
   across a decode glitch, a file loop, or a radio dropout. A backwards pts
   would make the tablet's nearest-pts overlay match ambiguous, and an
   ambiguous match is a box drawn on the wrong frame.
3. **Real, when the source has real timestamps.** Container timestamps are
   used as given (rebased). Only when a source genuinely has none is pts
   synthesised from the frame index or from arrival wall-clock, and
   :attr:`SourceInfo.pts_origin` then says so out loud. Silently faking
   timestamps would hide variable-rate sources and frame drops from the
   overlay-synchronisation code that has to cope with them.

``rtp_ts`` is left ``None`` by every source in this package, on purpose. The
tier-1 alignment in ``docs/CONTRACT.md`` needs the RTP timestamp *the browser
will actually see*, which is generated by the sender (aiortc) when the frame is
packetised -- not by the decoder that produced the frame. Deriving one here
from pts would look like tier-1 precision while being an invention. The stream
layer fills it in if it can.

The two backend readers (:class:`PyAVReader`, :class:`OpenCVReader`) live here
rather than in a module of their own because four of the five sources need
them; every heavy import inside them is deferred to :meth:`open` so that this
module, and the pure-logic tests, import fine on a machine with neither PyAV
nor OpenCV installed.
"""

