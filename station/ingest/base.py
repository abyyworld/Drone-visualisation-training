#: Used only when a source cannot report its own rate. 30 is the SIYI MK15
#: downlink default and a harmless guess for a file whose header is unhelpful.
DEFAULT_FPS = 30.0

#: Smallest gap we will ever leave between two consecutive pts values when
#: repairing a non-monotonic source. It has to survive the wire format:
#: ``FrameDetections.to_wire`` rounds pts to 4 decimal places, so anything
#: below 1e-4 s could collapse two frames onto one timestamp after
#: serialisation. 1 ms is comfortably above that and far below a frame period.
MIN_PTS_STEP = 1e-3


class IngestError(RuntimeError):
    """Base class for every failure raised by this package."""


class MissingDependencyError(IngestError):
    """A backend needed for this source type is not installed.

    Raised at :meth:`FrameSource.open` time, never at import time. The whole
    package must import cleanly on a laptop with no codecs so that the pure
    logic can be tested there.
    """

    def __init__(self, package: str, purpose: str, install: str) -> None:
        super().__init__(
            f"{purpose} needs the '{package}' package, which is not installed. "
            f"Install it with: {install}"
        )
        self.package = package
        self.install = install


class SourceUnavailableError(IngestError):
    """The source could not be opened, or an open source failed mid-stream."""


class SourceConfigError(IngestError, ValueError):
    """The SourceConfig cannot describe a source that could be opened."""


class PtsOrigin:
    """Where a source's presentation timestamps actually came from.

    Reported in :attr:`SourceInfo.pts_origin`. Downstream code is entitled to
    know: ``CONTAINER`` timestamps reflect real capture timing including
    jitter and drops, whereas ``FRAME_INDEX`` timestamps are a uniform fiction
    that will not line up with a variable-rate stream.
    """

    #: Real timestamps decoded from the container or stream.
    CONTAINER = "container"
    #: frame_index / nominal_fps. Used when the container has no timestamps.
    FRAME_INDEX = "frame_index"
    #: Arrival time on the station's monotonic clock. Used for capture devices,
    #: where arrival time is the only timing information that exists.
    WALL_CLOCK = "wall_clock"
    #: Computed by a generator that defines its own timeline (synthetic).
    GENERATED = "generated"
    #: Not yet known -- no frame has been read.
    UNKNOWN = "unknown"

    ALL = (CONTAINER, FRAME_INDEX, WALL_CLOCK, GENERATED, UNKNOWN)


@dataclass(frozen=True, slots=True, eq=False)
class Frame:
    """One decoded video frame on its way into the pipeline.

    Attributes:
        image: ``HxWx3`` ``uint8`` array in **BGR** channel order. BGR because
            that is what OpenCV and ultralytics both take by default, so the
            inference stage does not have to guess or convert.
        frame_id: Sequence number of frames *emitted by this source*, starting
            at 0. Frames dropped by rate decimation are not counted, so
            ``frame_id`` matches one-for-one with the ``frame_id`` in the
            incident log.
        pts: Presentation time in seconds on the media timeline. Zero-based
            and strictly increasing -- see the module docstring.
        wall_time: RFC 3339 UTC stamp of when the station handled the frame.
            Forensic only. Never used for overlay alignment.
        width: Frame width in pixels.
        height: Frame height in pixels.
        rtp_ts: 90 kHz RTP timestamp, when a layer that knows the real one
            supplies it. Always ``None`` from this package -- see module
            docstring.
        source_pts: The raw timestamp from the container, before rebasing and
            monotonicity repair. Kept for forensics; ``None`` when the source
            had no timestamp for this frame.
        pts_synthesised: True when :attr:`pts` for *this* frame was invented
            rather than decoded. A source can be mostly real and occasionally
            not.

    ``eq`` is disabled: two frames are never meaningfully "equal", and the
    generated ``__eq__`` would compare numpy arrays and raise on the
    ambiguous-truth-value trap.
    """

    image: np.ndarray
    frame_id: int
    pts: float
    wall_time: str = field(default_factory=utc_now_iso)
    width: int = 0
    height: int = 0
    rtp_ts: int | None = None
    source_pts: float | None = None
    pts_synthesised: bool = False

    def __post_init__(self) -> None:
        img = self.image
        if not isinstance(img, np.ndarray):
            raise TypeError(f"Frame.image must be a numpy array, got {type(img).__name__}")
        if img.ndim != 3 or img.shape[2] != 3:
            raise ValueError(f"Frame.image must be HxWx3 BGR, got shape {img.shape}")
        if img.dtype != np.uint8:
            raise ValueError(f"Frame.image must be uint8, got {img.dtype}")
        if not math.isfinite(float(self.pts)):
            raise ValueError(f"Frame.pts must be finite, got {self.pts!r}")
        object.__setattr__(self, "pts", float(self.pts))
        if self.width <= 0:
            object.__setattr__(self, "width", int(img.shape[1]))
        if self.height <= 0:
            object.__setattr__(self, "height", int(img.shape[0]))
        if (self.height, self.width) != img.shape[:2]:
            raise ValueError(
                f"Frame declares {self.width}x{self.height} but image is "
                f"{img.shape[1]}x{img.shape[0]}"
            )

    @property
    def shape(self) -> tuple[int, int]:
        """``(width, height)`` in pixels."""
        return (self.width, self.height)

    def __repr__(self) -> str:  # arrays must never be printed into a log line
        return (
            f"Frame(frame_id={self.frame_id}, pts={self.pts:.4f}, "
            f"{self.width}x{self.height}, synthesised_pts={self.pts_synthesised})"
        )


@dataclass(frozen=True, slots=True)
class SourceInfo:
    """What a source is and how it behaves. Available after :meth:`open`.

    Attributes:
        type: The ``SourceConfig.type`` this source was built from.
        uri: The source URI, used as ``FrameDetections.source_id``.
        width: Native frame width, 0 until the first frame confirms it.
        height: Native frame height, 0 until the first frame confirms it.
        fps: Native source rate, before decimation.
        target_fps: Rate cap applied by this layer, or ``None`` for source rate.
        backend: Which decoder is actually running ("PyAV", "OpenCV", ...).
        pts_origin: One of :class:`PtsOrigin`. Read it before trusting pts to
            reflect real capture timing.
        is_live: True when frames arrive in real time and cannot be rewound.
            A live source that is not read fast enough loses frames; a file
            source just blocks.
        notes: Human-readable caveats accumulated while opening and reading,
            e.g. that timestamps had to be synthesised. Intended for the
            operator-facing log line at startup.
    """

    type: str
    uri: str
    width: int = 0
    height: int = 0
    fps: float = DEFAULT_FPS
    target_fps: float | None = None
    backend: str = "unknown"
    pts_origin: str = PtsOrigin.UNKNOWN
    is_live: bool = False
    notes: tuple[str, ...] = ()

    @property
    def resolution(self) -> tuple[int, int]:
        """``(width, height)`` in pixels; ``(0, 0)`` before the first frame."""
        return (self.width, self.height)

    @property
    def output_fps(self) -> float:
        """Nominal rate handed downstream, after decimation."""
        if self.target_fps is None:
            return self.fps
        return min(self.fps, float(self.target_fps))

    def describe(self) -> str:
        """One-line summary for the startup log."""
        res = f"{self.width}x{self.height}" if self.width else "size unknown"
        rate = f"{self.fps:.3g} fps"
        if self.target_fps is not None:
            rate += f" -> {self.output_fps:.3g} fps"
        bits = [f"{self.type}:{self.uri or '-'}", res, rate, f"via {self.backend}", f"pts={self.pts_origin}"]
        line = " | ".join(bits)
        if self.notes:
            line += " | " + "; ".join(self.notes)
        return line


@dataclass(slots=True)
class SourceStats:
    """Counters a pipeline needs to fill in :class:`PipelineStatus`.

    Deliberately separates the three ways a frame can fail to reach inference:
    decimation (intentional), decode errors (a fault), and reconnects (a link
    problem). Collapsing them into one "dropped" number would hide a failing
    radio behind a configured frame-rate cap.
    """

    frames_in: int = 0
    frames_out: int = 0
    #: Dropped on purpose to honour ``target_fps``.
    decimated: int = 0
    #: Frames whose pts had to be repaired to stay monotonic.
    pts_repairs: int = 0
    #: Frames whose pts had to be invented because the source supplied none.
    pts_synthesised: int = 0
    reconnects: int = 0
    decode_errors: int = 0
    #: True while a live source is between attempts. The status layer turns
    #: this into an operator-facing note; it is a pipeline fact, not a claim
    #: about the scene.
    reconnecting: bool = False
    last_error: str | None = None
    opened_monotonic: float | None = None

    @property
    def elapsed_s(self) -> float:
        """Wall seconds since the source was opened."""
        if self.opened_monotonic is None:
            return 0.0
        return max(0.0, time.monotonic() - self.opened_monotonic)

    @property
    def measured_source_fps(self) -> float | None:
        """Frames arriving per wall second, or ``None`` before enough data.

        For a file decoded flat out this is far above the file's own rate --
        that is honest, not a bug: it is the rate at which frames really
        arrived.
        """
        elapsed = self.elapsed_s
        if elapsed <= 0.0 or self.frames_in < 2:
            return None
        return self.frames_in / elapsed

    @property
    def measured_output_fps(self) -> float | None:
        """Frames handed downstream per wall second."""
        elapsed = self.elapsed_s
        if elapsed <= 0.0 or self.frames_out < 2:
            return None
        return self.frames_out / elapsed


class PtsClock:
    """Turns whatever timestamps a source offers into a lawful media timeline.

    Guarantees the three properties in the module docstring: zero-based,
    strictly monotonic, and honest about where each value came from. One
    instance per source; not thread-safe (a source is read by one thread).

    Args:
        nominal_fps: Source rate, used for the synthetic step and for the size
            of the gap inserted at a loop point.
        mode: Preferred origin -- :attr:`PtsOrigin.CONTAINER` for anything with
            real timestamps, :attr:`PtsOrigin.WALL_CLOCK` for capture devices,
            :attr:`PtsOrigin.FRAME_INDEX` for files whose container has none.
        min_step: Smallest permitted increment when repairing a stall or a
            backwards jump.
    """

    def __init__(
        self,
        nominal_fps: float | None = None,
        mode: str = PtsOrigin.CONTAINER,
        min_step: float = MIN_PTS_STEP,
    ) -> None:
        if mode not in PtsOrigin.ALL:
            raise ValueError(f"unknown pts mode {mode!r}; expected one of {PtsOrigin.ALL}")
        fps = float(nominal_fps) if nominal_fps and nominal_fps > 0 else DEFAULT_FPS
        self._step = 1.0 / fps
        self._mode = mode
        self._min_step = max(float(min_step), 0.0) or MIN_PTS_STEP
        self._raw_origin: float | None = None
        self._wall_origin: float | None = None
        self._offset = 0.0
        self._pending_advance = 0.0
        self._last: float | None = None
        self._count = 0
        self.repairs = 0
        self.synthesised = 0
        #: Origin of the most recent stamp; the source copies this into
        #: SourceInfo once the first frame has proved what the source really is.
        self.origin = PtsOrigin.UNKNOWN

    @property
    def last(self) -> float | None:
        """Most recently issued pts, or ``None`` before the first frame."""
        return self._last

    @property
    def nominal_step(self) -> float:
        """One nominal frame period in seconds."""
        return self._step

    def stamp(self, raw_pts: float | None = None) -> float:
        """Map one source timestamp onto the media timeline.

        Args:
            raw_pts: The container's timestamp in seconds, or ``None`` when the
                source has none for this frame.

        Returns:
            A strictly increasing, zero-based media timestamp in seconds.
        """
        usable = raw_pts is not None and math.isfinite(float(raw_pts))
        if usable and self._mode in (PtsOrigin.CONTAINER, PtsOrigin.GENERATED):
            raw = float(raw_pts)  # type: ignore[arg-type]
            if self._raw_origin is None:
                self._raw_origin = raw
                self._offset = self._resume_base()
            candidate = (raw - self._raw_origin) + self._offset
            origin = self._mode
            synthesised = False
        elif self._mode == PtsOrigin.WALL_CLOCK:
            now = time.monotonic()
            if self._wall_origin is None:
                self._wall_origin = now
                self._offset = self._resume_base()
            candidate = (now - self._wall_origin) + self._offset
            origin = PtsOrigin.WALL_CLOCK
            synthesised = True
        else:
            # No timestamp and no clock worth reading: uniform frame periods.
            # Honest but lossy -- a dropped frame is invisible in this timeline,
            # which is exactly why pts_origin is published.
            if self._last is None:
                candidate = self._resume_base()
            else:
                candidate = self._last + self._step
            origin = PtsOrigin.FRAME_INDEX
            synthesised = True

        if synthesised:
            self.synthesised += 1

        # Monotonicity is repaired rather than trusted. Real streams do go
        # backwards: a decoder resync, an RTSP source that restarts its clock
        # without us noticing, a container with a broken index. Downstream,
        # a repeated or reversed pts means the tablet cannot tell which frame a
        # box belongs to, so we force a gap and count it.
        if self._last is not None and candidate <= self._last + (self._min_step / 2.0):
            candidate = self._last + self._min_step
            self.repairs += 1

        self._last = candidate
        self._count += 1
        self._pending_advance = 0.0
        self.origin = origin
        return candidate

    def discontinuity(self, advance_s: float | None = None) -> None:
        """Declare that the underlying stream restarted its own clock.

        Called on a file loop and after every reconnect. The media timeline
        continues forward across the seam instead of jumping back to zero,
        because the tablet's overlay buffer matches on pts and a timeline that
        rewinds would match new detections against old frames.

        Args:
            advance_s: How far to advance the media timeline across the seam.
                For a reconnect, pass the measured outage in wall seconds so the
                timeline reflects the time the operator actually lost. For a
                loop, one frame period (the default) keeps playback continuous.
        """
        advance = self._step if advance_s is None else max(float(advance_s), self._min_step)
        self._pending_advance = advance
        self._raw_origin = None
        self._wall_origin = None

    def _resume_base(self) -> float:
        """Media time the next epoch starts at."""
        if self._last is None:
            return 0.0
        return self._last + max(self._pending_advance, self._min_step)


class FpsDecimator:
    """Drops frames to honour ``SourceConfig.target_fps``, using pts.

    Decimating by pts rather than by sleeping matters twice over. On a live
    source, sleeping inside the read loop would let the socket buffer fill and
    turn a rate cap into growing latency -- on a fire ground, latency is the
    one thing the overlay cannot buy back. On a file source, sleeping would
    make a regression test run in real time instead of in milliseconds.

    Dropping frames can never break pts monotonicity: it only removes values
    from an already increasing sequence.
    """

    def __init__(self, target_fps: float | None) -> None:
        if target_fps is not None and float(target_fps) <= 0:
            raise SourceConfigError(f"source.target_fps must be positive or null, got {target_fps}")
        self._period = None if target_fps is None else 1.0 / float(target_fps)
        self._next_due: float | None = None
        self.dropped = 0

    @property
    def period(self) -> float | None:
        """Minimum media-seconds between emitted frames, or ``None``."""
        return self._period

    def accept(self, pts: float) -> bool:
        """Decide whether the frame at ``pts`` should be handed downstream."""
        if self._period is None:
            return True
        if self._next_due is None:  # the first frame is always kept
            self._next_due = pts + self._period
            return True
        if pts + 1e-9 >= self._next_due:
            self._next_due += self._period
            # After a gap (reconnect, stall) the schedule is far behind; resync
            # instead of emitting a burst of back-to-back frames to catch up.
            if self._next_due <= pts:
                self._next_due = pts + self._period
            return True
        self.dropped += 1
        return False

    def reset(self) -> None:
        """Forget the schedule, e.g. across a discontinuity."""
        self._next_due = None


class ReconnectPolicy:
    """Exponential backoff with jitter, interruptible by :meth:`cancel`.

    ``SourceConfig.reconnect_s`` sets the first delay. Backing off matters
    because the common failure is not a one-off: the drone is behind a ridge
    and will be for a while, and hammering the radio link with reconnects for
    minutes costs bandwidth the video needs when it does come back. Capping
    the backoff matters just as much -- the link *will* return, and the
    pipeline has to notice within seconds rather than minutes.
    """

    def __init__(
        self,
        base_delay_s: float,
        max_delay_s: float = 15.0,
        max_attempts: int | None = None,
        jitter: float = 0.2,
    ) -> None:
        self._base = max(float(base_delay_s), 0.0)
        self._max = max(float(max_delay_s), self._base)
        self._max_attempts = max_attempts
        self._jitter = min(max(float(jitter), 0.0), 1.0)
        self._cancel = threading.Event()
        self.attempts = 0

    @property
    def exhausted(self) -> bool:
        """True when the attempt budget is used up (never, by default)."""
        return self._max_attempts is not None and self.attempts >= self._max_attempts

    @property
    def cancelled(self) -> bool:
        return self._cancel.is_set()

    def reset(self) -> None:
        """Called after a successful read: the link is healthy again."""
        self.attempts = 0

    def cancel(self) -> None:
        """Interrupt a waiting :meth:`wait`, from any thread.

        This is how ``close()`` gets a source out of a reconnect loop without
        waiting out the backoff.
        """
        self._cancel.set()

    def next_delay(self) -> float:
        """Delay before the next attempt, in seconds."""
        delay = min(self._base * (2.0 ** self.attempts), self._max)
        if self._jitter:
            # Deterministic jitter (derived from the attempt count) rather than
            # random: it still de-synchronises retries between several sources
            # sharing a link, and it keeps test runs reproducible.
            phase = ((self.attempts * 2654435761) % 1000) / 1000.0
            delay *= 1.0 + self._jitter * (phase - 0.5) * 2.0
        return max(delay, 0.0)

    def wait(self) -> bool:
        """Sleep for the next backoff interval.

        Returns:
            True if the wait completed, False if it was cancelled by
            :meth:`cancel` (the source is closing and must not retry).
        """
        delay = self.next_delay()
        self.attempts += 1
        if delay <= 0.0:
            return not self._cancel.is_set()
        return not self._cancel.wait(delay)


