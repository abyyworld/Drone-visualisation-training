class PyAVReader:
    """One PyAV container, decoded to BGR frames with container timestamps.

    Preferred over OpenCV everywhere it works: PyAV exposes real presentation
    timestamps and the demuxer options that make an RTSP link low-latency,
    both of which ``cv2.VideoCapture`` hides behind a global environment
    variable.
    """

    def __init__(
        self,
        uri: str,
        *,
        options: dict[str, str] | None = None,
        container_format: str | None = None,
        open_timeout_s: float | None = 8.0,
        read_timeout_s: float | None = 8.0,
        thread_type: str = "AUTO",
    ) -> None:
        self.uri = uri
        self.backend = "PyAV"
        self.width = 0
        self.height = 0
        self.fps = DEFAULT_FPS
        self.has_container_pts = False
        self._options = dict(options or {})
        self._format = container_format
        self._open_timeout = open_timeout_s
        self._read_timeout = read_timeout_s
        self._thread_type = thread_type
        self._av: Any = None
        self._container: Any = None
        self._stream: Any = None
        self._frames: Iterator[Any] | None = None
        self._time_base: float | None = None

    def open(self) -> None:
        """Open the container and select its first video stream.

        Raises:
            MissingDependencyError: PyAV is not installed.
            SourceUnavailableError: the container could not be opened or has no
                video stream.
        """
        try:
            import av  # noqa: PLC0415 -- lazy on purpose; see module docstring
        except ImportError as exc:
            raise MissingDependencyError("av", f"decoding {self.uri!r}", "pip install av") from exc
        self._av = av
        kwargs: dict[str, Any] = {"options": self._options}
        if self._format:
            kwargs["format"] = self._format
        if self._open_timeout is not None or self._read_timeout is not None:
            kwargs["timeout"] = (self._open_timeout, self._read_timeout)
        try:
            try:
                self._container = av.open(self.uri, **kwargs)
            except TypeError:
                # PyAV < 9 has no timeout argument. Better to open without one
                # than to refuse to run on an older wheel.
                kwargs.pop("timeout", None)
                self._container = av.open(self.uri, **kwargs)
        except Exception as exc:  # av raises a family of FFmpeg errors
            raise SourceUnavailableError(f"PyAV could not open {self.uri!r}: {exc}") from exc

        streams = self._container.streams.video
        if not streams:
            self.close()
            raise SourceUnavailableError(f"{self.uri!r} has no video stream")
        self._stream = streams[0]
        try:
            # Frame-threaded decoding adds latency (the decoder holds frames
            # back); slice threading does not. AUTO picks per codec, and for
            # H.264 over a radio link the difference is visible.
            self._stream.thread_type = self._thread_type
        except Exception:  # pragma: no cover - older PyAV builds
            pass
        ctx = self._stream.codec_context
        self.width = int(getattr(ctx, "width", 0) or 0)
        self.height = int(getattr(ctx, "height", 0) or 0)
        self.fps = _rate_of(self._stream)
        tb = getattr(self._stream, "time_base", None)
        self._time_base = float(tb) if tb else None
        self._frames = self._container.decode(self._stream)

    def next(self) -> tuple[np.ndarray, float | None] | None:
        """Decode the next frame.

        Returns:
            ``(bgr_image, raw_pts_seconds_or_None)``, or ``None`` at clean end
            of stream.

        Raises:
            SourceUnavailableError: the stream failed mid-decode. Callers that
                can reconnect treat this the same as end of stream.
        """
        if self._frames is None:
            raise SourceUnavailableError("PyAVReader.next() before open()")
        try:
            frame = next(self._frames, None)
        except StopIteration:  # pragma: no cover - next() default covers this
            frame = None
        except Exception as exc:
            raise SourceUnavailableError(f"decode failed on {self.uri!r}: {exc}") from exc
        if frame is None:
            return None
        pts = self._frame_pts(frame)
        if pts is not None:
            self.has_container_pts = True
        try:
            image = frame.to_ndarray(format="bgr24")
        except Exception as exc:
            raise SourceUnavailableError(f"colour conversion failed on {self.uri!r}: {exc}") from exc
        if not self.width or not self.height:
            self.height, self.width = int(image.shape[0]), int(image.shape[1])
        return image, pts

    def _frame_pts(self, frame: Any) -> float | None:
        """Seconds on the container timeline, or ``None`` if it has none."""
        t = getattr(frame, "time", None)  # PyAV already applies time_base here
        if t is not None and math.isfinite(float(t)):
            return float(t)
        raw = getattr(frame, "pts", None)
        if raw is None or self._time_base is None:
            return None
        return float(raw) * self._time_base

    def seek_start(self) -> None:
        """Rewind to the beginning, for a looping file source.

        Raises:
            SourceUnavailableError: the container is not seekable.
        """
        if self._container is None or self._stream is None:
            raise SourceUnavailableError("PyAVReader.seek_start() before open()")
        try:
            self._container.seek(0, stream=self._stream)
            self._frames = self._container.decode(self._stream)
        except Exception as exc:
            raise SourceUnavailableError(f"cannot rewind {self.uri!r}: {exc}") from exc

    def close(self) -> None:
        """Release the container. Safe to call twice."""
        self._frames = None
        self._stream = None
        container, self._container = self._container, None
        if container is not None:
            try:
                container.close()
            except Exception:  # pragma: no cover - closing a dead socket
                pass


class OpenCVReader:
    """``cv2.VideoCapture`` fallback: files, RTSP/RTMP URLs, capture devices.

    Used where PyAV is absent, and preferred for USB capture devices, whose
    pixel-format and buffering controls OpenCV exposes directly.
    """

    def __init__(
        self,
        target: str | int,
        *,
        api_preference: str | None = None,
        ffmpeg_options: str | None = None,
        use_timestamps: bool = True,
        buffer_size: int | None = None,
        properties: Sequence[tuple[str, float]] = (),
    ) -> None:
        self.target = target
        self.backend = "OpenCV"
        self.width = 0
        self.height = 0
        self.fps = DEFAULT_FPS
        self.has_container_pts = False
        self._api_preference = api_preference
        self._ffmpeg_options = ffmpeg_options
        self._use_timestamps = use_timestamps
        self._buffer_size = buffer_size
        self._properties = tuple(properties)
        self._cap: Any = None
        self._cv2: Any = None
        self._last_pos_ms: float | None = None
        self._flat_pos_count = 0

    def open(self) -> None:
        """Open the capture.

        Raises:
            MissingDependencyError: OpenCV is not installed.
            SourceUnavailableError: the capture would not open.
        """
        try:
            import cv2  # noqa: PLC0415 -- lazy on purpose
        except ImportError as exc:
            raise MissingDependencyError(
                "cv2", f"capturing {self.target!r}", "pip install opencv-python-headless"
            ) from exc
        self._cv2 = cv2
        if self._ffmpeg_options:
            # OpenCV's FFmpeg backend takes demuxer options only through this
            # environment variable, read when VideoCapture is constructed --
            # there is no per-capture API. setdefault so an operator who set it
            # deliberately in the environment still wins.
            os.environ.setdefault("OPENCV_FFMPEG_CAPTURE_OPTIONS", self._ffmpeg_options)
        api = getattr(cv2, self._api_preference, None) if self._api_preference else None
        try:
            cap = cv2.VideoCapture(self.target, api) if api is not None else cv2.VideoCapture(self.target)
        except Exception as exc:
            raise SourceUnavailableError(f"OpenCV could not open {self.target!r}: {exc}") from exc
        if not cap.isOpened():
            cap.release()
            raise SourceUnavailableError(f"OpenCV could not open {self.target!r}")
        # Order matters on UVC devices: the pixel format has to be set before
        # the frame size, or the driver silently keeps the old format and
        # caps the resolution (the classic "1080p capture card runs at 5 fps"
        # trap -- it fell back to raw YUY2 over USB 2).
        for name, value in self._properties:
            prop = getattr(cv2, name, None)
            if prop is None:
                continue
            cap.set(prop, value)
        if self._buffer_size is not None:
            # One-frame buffer: on a live source we want the newest frame, not
            # a queue of stale ones. Not honoured by every backend.
            cap.set(cv2.CAP_PROP_BUFFERSIZE, float(self._buffer_size))
        self._cap = cap
        self.width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH) or 0)
        self.height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT) or 0)
        reported = float(cap.get(cv2.CAP_PROP_FPS) or 0.0)
        self.fps = reported if 0.0 < reported < 1000.0 else DEFAULT_FPS

    def next(self) -> tuple[np.ndarray, float | None] | None:
        """Grab the next frame, with its container timestamp when there is one."""
        if self._cap is None:
            raise SourceUnavailableError("OpenCVReader.next() before open()")
        cv2 = self._cv2
        pos_ms: float | None = None
        if self._use_timestamps:
            # Read the position *before* read(). With the FFmpeg backend
            # CAP_PROP_POS_MSEC advances as soon as a frame is grabbed, so
            # reading it afterwards gives the timestamp of the *next* frame --
            # a one-frame overlay offset that is invisible until something is
            # moving fast, which is exactly when it matters.
            raw = self._cap.get(cv2.CAP_PROP_POS_MSEC)
            if raw is not None and math.isfinite(raw) and raw >= 0.0:
                pos_ms = float(raw)
        try:
            ok, image = self._cap.read()
        except Exception as exc:
            raise SourceUnavailableError(f"read failed on {self.target!r}: {exc}") from exc
        if not ok or image is None:
            return None
        if image.ndim == 2:  # some capture drivers hand back single-channel
            image = cv2.cvtColor(image, cv2.COLOR_GRAY2BGR)
        if not self.width or not self.height:
            self.height, self.width = int(image.shape[0]), int(image.shape[1])
        pts = self._vet_timestamp(pos_ms)
        if pts is not None:
            self.has_container_pts = True
        return image, pts

    def _vet_timestamp(self, pos_ms: float | None) -> float | None:
        """Reject a position counter that is not actually a clock.

        Plenty of backends return a constant 0.0 for POS_MSEC. Feeding that to
        the pts clock would produce a monotonicity repair on every single frame
        and a timeline made entirely of 1 ms steps, which would look valid and
        be nonsense. Detect it once, then stop asking.
        """
        if pos_ms is None:
            return None
        if self._last_pos_ms is not None and pos_ms <= self._last_pos_ms:
            self._flat_pos_count += 1
            if self._flat_pos_count >= 3:
                self._use_timestamps = False
                return None
            return None
        self._last_pos_ms = pos_ms
        self._flat_pos_count = 0
        return pos_ms / 1000.0

    def close(self) -> None:
        """Release the capture. Safe to call twice."""
        cap, self._cap = self._cap, None
        if cap is not None:
            try:
                cap.release()
            except Exception:  # pragma: no cover
                pass


def _rate_of(stream: Any) -> float:
    """Best available nominal frame rate for a PyAV video stream."""
    for attr in ("average_rate", "guessed_rate", "base_rate"):
        rate = getattr(stream, attr, None)
        if rate:
            try:
                value = float(rate)
            except (TypeError, ValueError):
                continue
            if 0.0 < value < 1000.0:
                return value
    return DEFAULT_FPS


class FrameSource(abc.ABC):
    """Abstract video source: open it, iterate frames, close it.

    Subclasses implement three hooks -- :meth:`_open_impl`, :meth:`_read_raw`
    and :meth:`_close_impl` -- and inherit pts normalisation, rate decimation,
    frame numbering and statistics from here, so that every source in the
    system produces timestamps with identical semantics. That uniformity is
    the point of the seam: a bug in pts handling should be fixable in one
    place, not five.

    Usage::

        with open_source(cfg) as src:
            for frame in src:
                ...

    Threading: a source is read by one thread. :meth:`close` is the exception
    and may be called from another thread to break a blocking read or a
    reconnect backoff.
    """

    def __init__(self, cfg: SourceConfig, *, source_type: str, uri: str | None = None) -> None:
        self.cfg = cfg
        self._info = SourceInfo(
            type=source_type,
            uri=uri if uri is not None else cfg.uri,
            target_fps=cfg.target_fps,
        )
        self._stats = SourceStats()
        self._decimator = FpsDecimator(cfg.target_fps)
        self._clock: PtsClock | None = None
        self._next_frame_id = 0
        self._opened = False
        self._ended = False
        self._closing = False

    # -- public API ---------------------------------------------------------

    @property
    def info(self) -> SourceInfo:
        """Resolution, rate, URI, backend and pts provenance.

        Populated by :meth:`open` and refined once the first frame confirms the
        real frame size and whether the source had timestamps at all.
        """
        return self._info

    @property
    def stats(self) -> SourceStats:
        """Live counters. The same object throughout the source's life."""
        return self._stats

    @property
    def is_open(self) -> bool:
        return self._opened

    @property
    def is_exhausted(self) -> bool:
        """True once :meth:`read` has returned ``None``."""
        return self._ended

    def open(self) -> "FrameSource":
        """Open the underlying source. Idempotent.

        Returns:
            ``self``, so ``src = FileSource(cfg).open()`` reads well.

        Raises:
            MissingDependencyError: the backend this source needs is absent.
            SourceUnavailableError: the source exists but would not open.
        """
        if self._opened:
            return self
        self._closing = False
        self._open_impl()
        self._opened = True
        self._ended = False
        self._stats.opened_monotonic = time.monotonic()
        return self

    def close(self) -> None:
        """Release the source. Idempotent, and safe from another thread."""
        self._closing = True
        if not self._opened:
            self._close_impl()
            return
        self._opened = False
        self._close_impl()

    def read(self) -> Frame | None:
        """Return the next frame, or ``None`` when the source is finished.

        A live source only returns ``None`` when it has given up reconnecting
        or has been closed; a file returns ``None`` at end of file (unless
        ``SourceConfig.loop``).

        Raises:
            IngestError: the source has not been opened.
        """
        if not self._opened:
            raise IngestError(f"{type(self).__name__}.read() called before open()")
        clock = self._clock
        if clock is None:  # pragma: no cover - _open_impl always sets it
            raise IngestError(f"{type(self).__name__} did not initialise its pts clock")
        while True:
            raw = self._read_raw()
            if raw is None:
                self._ended = True
                return None
            image, raw_pts = raw
            self._stats.frames_in += 1
            pts = clock.stamp(raw_pts)
            self._stats.pts_repairs = clock.repairs
            self._stats.pts_synthesised = clock.synthesised
            if not self._decimator.accept(pts):
                self._stats.decimated = self._decimator.dropped
                continue
            frame = Frame(
                image=image,
                frame_id=self._next_frame_id,
                pts=pts,
                wall_time=utc_now_iso(),
                rtp_ts=None,  # only the sender knows the real one; see module docstring
                source_pts=raw_pts,
                pts_synthesised=raw_pts is None,
            )
            self._next_frame_id += 1
            self._stats.frames_out += 1
            if self._next_frame_id == 1:
                self._observe_first_frame(frame, clock)
            return frame

    def __iter__(self) -> Iterator[Frame]:
        """Iterate frames until the source is exhausted, opening it if needed."""
        if not self._opened:
            self.open()
        return self

    def __next__(self) -> Frame:
        frame = self.read()
        if frame is None:
            raise StopIteration
        return frame

    def __enter__(self) -> "FrameSource":
        return self.open()

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        self.close()

    def __repr__(self) -> str:
        return f"{type(self).__name__}({self._info.describe()})"

    # -- helpers for subclasses --------------------------------------------

    def _set_info(self, **changes: Any) -> None:
        """Update the published :class:`SourceInfo`."""
        self._info = replace(self._info, **changes)

    def _add_note(self, note: str) -> None:
        """Record an operator-facing caveat, once."""
        if note not in self._info.notes:
            self._info = replace(self._info, notes=self._info.notes + (note,))

    def _init_clock(self, mode: str, fps: float | None = None) -> PtsClock:
        """Create the pts clock. Every ``_open_impl`` must call this."""
        self._clock = PtsClock(nominal_fps=fps if fps is not None else self._info.fps, mode=mode)
        return self._clock

    def _observe_first_frame(self, frame: Frame, clock: PtsClock) -> None:
        """Correct :attr:`info` once reality is known.

        The header's idea of the frame size is not always right, and whether a
        container really carries timestamps is only knowable after decoding
        something. Publishing the guess and never correcting it would leave
        ``pts_origin`` claiming ``container`` on a stream that has none.
        """
        changes: dict[str, Any] = {"pts_origin": clock.origin}
        if frame.width and frame.height and (frame.width, frame.height) != self._info.resolution:
            changes["width"] = frame.width
            changes["height"] = frame.height
        self._set_info(**changes)
        if clock.origin == PtsOrigin.FRAME_INDEX:
            self._add_note(
                f"source supplied no timestamps; pts synthesised from frame index at "
                f"{self._info.fps:.4g} fps"
            )
        elif clock.origin == PtsOrigin.WALL_CLOCK:
            self._add_note("device capture; pts taken from frame arrival time")

    # -- subclass hooks -----------------------------------------------------

    @abc.abstractmethod
    def _open_impl(self) -> None:
        """Open the backend and call :meth:`_init_clock`."""

    @abc.abstractmethod
    def _read_raw(self) -> tuple[np.ndarray, float | None] | None:
        """Return ``(bgr_image, raw_pts_or_None)``, or ``None`` when finished."""

    @abc.abstractmethod
    def _close_impl(self) -> None:
        """Release backend resources. Must tolerate being called twice."""


class ReconnectingSource(FrameSource):
    """A :class:`FrameSource` backed by a reader that may fail and be re-opened.

    Shared by every live source (RTSP, RTMP, HDMI). The behaviour it exists to
    guarantee: *a link that drops comes back without anybody touching the
    laptop*. Ground stations are set up on a truck bonnet and then everyone
    walks away from them.

    Two details that are easy to get wrong and matter downstream:

    * The media timeline advances across the outage by the measured wall-clock
      gap, so a 12 s dropout leaves a 12 s hole in pts rather than pretending
      the frames were contiguous. The incident log then shows what was really
      missed.
    * The decimator is reset at the seam, so the first frame after a reconnect
      is always delivered rather than waiting out a rate-limit schedule
      inherited from before the outage.
    """

    def __init__(
        self,
        cfg: SourceConfig,
        *,
        source_type: str,
        uri: str | None = None,
        max_reconnect_attempts: int | None = None,
        max_backoff_s: float = 15.0,
    ) -> None:
        super().__init__(cfg, source_type=source_type, uri=uri)
        self._reader: FrameReader | None = None
        self._policy = ReconnectPolicy(
            base_delay_s=cfg.reconnect_s,
            max_delay_s=max_backoff_s,
            max_attempts=max_reconnect_attempts,
        )
        self._outage_started: float | None = None

    @abc.abstractmethod
    def _connect(self) -> FrameReader:
        """Build and open a fresh reader, or raise.

        Returning an already-open reader (rather than one this class opens) is
        what lets a subclass try several backends and pick whichever came up.
        """

    def _pts_mode(self) -> str:
        """Preferred pts origin. Overridden by capture devices."""
        return PtsOrigin.CONTAINER

    def _open_impl(self) -> None:
        reader = self._connect()
        self._reader = reader
        self._set_info(
            width=reader.width,
            height=reader.height,
            fps=reader.fps,
            backend=reader.backend,
            is_live=True,
        )
        self._init_clock(self._pts_mode(), reader.fps)
        self._stats.reconnecting = False

    def _read_raw(self) -> tuple[np.ndarray, float | None] | None:
        while True:
            item: tuple[np.ndarray, float | None] | None = None
            if self._reader is not None:
                try:
                    item = self._reader.next()
                except IngestError as exc:
                    self._stats.decode_errors += 1
                    self._stats.last_error = str(exc)
                    item = None
            if item is not None:
                if self._stats.reconnecting:
                    self._finish_outage()
                self._policy.reset()
                return item
            if self._closing or self._policy.exhausted or self._policy.cancelled:
                return None
            if not self._reconnect():
                return None

    def _reconnect(self) -> bool:
        """Tear down, back off, and try again.

        Returns:
            True if a reader is open again, False if the source should stop
            (closed, cancelled, or out of attempts).
        """
        if self._outage_started is None:
            self._outage_started = time.monotonic()
        self._stats.reconnecting = True
        if self._reader is not None:
            try:
                self._reader.close()
            except Exception:  # pragma: no cover - closing a broken socket
                pass
            self._reader = None
        while not self._closing:
            if not self._policy.wait():  # cancelled by close()
                return False
            if self._policy.exhausted:
                self._stats.last_error = (
                    f"giving up on {self._info.uri!r} after {self._policy.attempts} attempts"
                )
                return False
            try:
                reader = self._connect()
            except MissingDependencyError:
                raise  # retrying will not install a package
            except IngestError as exc:
                self._stats.last_error = str(exc)
                continue
            self._reader = reader
            self._stats.reconnects += 1
            if reader.width and reader.height:
                self._set_info(width=reader.width, height=reader.height, backend=reader.backend)
            return True
        return False

    def _finish_outage(self) -> None:
        """Close the timeline gap once frames are flowing again."""
        gap = 0.0
        if self._outage_started is not None:
            gap = max(0.0, time.monotonic() - self._outage_started)
        self._outage_started = None
        self._stats.reconnecting = False
        clock = self._clock
        if clock is not None:
            # The stream restarted its own clock at zero. Continue our timeline
            # forward by the real outage so pts keeps meaning "time since the
            # session began" -- a timeline that rewound would make the tablet
            # match fresh detections against frames from before the dropout.
            clock.discontinuity(gap)
        self._decimator.reset()
        self._add_note(f"reconnected after {gap:.1f}s")

    def _close_impl(self) -> None:
        self._policy.cancel()
        reader, self._reader = self._reader, None
        if reader is not None:
            try:
                reader.close()
            except Exception:  # pragma: no cover
                pass
